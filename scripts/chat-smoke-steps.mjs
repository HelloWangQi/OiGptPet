import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
export async function checkChat(desktop, page, pet) {
  const file = await desktop.evaluate(({ app }) => {
    globalThis.__chatOriginalFetch = globalThis.fetch;
    globalThis.__chatRequestCount = 0;
    globalThis.fetch = async (url, options) => {
      globalThis.__chatRequestCount++;
      if (options.headers.Authorization !== 'Bearer smoke-key-not-real') throw new Error('Unexpected auth format');
      const body = JSON.parse(options.body);
      if (url !== 'https://api.openai.com/v1/responses' || body.store !== false || body.stream !== true) throw new Error('Unexpected request');
      return new Response(new ReadableStream({ start(controller) {
        globalThis.__chatStream = controller;
        controller.enqueue(new TextEncoder().encode('data: {"type":"response.output_text.delta","delta":"你好，","output_index":0,"content_index":0}\n\n'));
      } }), { headers: { 'content-type': 'text/event-stream' } });
    };
    return app.getPath('userData') + '/chat-settings.json';
  });
  try {
    assert.equal(await page.locator('.chat-panel details').evaluate(panel => panel.open), true);
    assert.equal(await page.locator('#chat-send').isDisabled(), true);
    await page.locator('#chat-check').click();
    await page.waitForFunction(() => document.querySelector('#chat-check-status').textContent.includes('请先填写'));
    await page.locator('#chat-model').fill('invalid model!'); await page.locator('#chat-key').fill('smoke-key-not-real');
    await page.locator('#chat-save').click();
    await page.waitForFunction(() => document.querySelector('#chat-status').textContent.includes('模型 ID'));
    await assert.rejects(readFile(file), { code: 'ENOENT' });
    await page.locator('#chat-model').fill('test-model'); await page.locator('#chat-key').fill('smoke-key-not-real');
    await page.locator('#chat-save').click();
    await page.waitForFunction(() => document.querySelector('#chat-status').textContent.includes('配置已保存'));
    assert.equal(await page.locator('#chat-key').inputValue(), '');
    assert.equal((await readFile(file, 'utf8')).includes('smoke-key-not-real'), false);
    const settings = await page.evaluate(() => window.petDesktop.getChatSettings()); assert.equal('apiKey' in settings, false); assert.equal('key' in settings, false);
    const beforeCheck = await page.evaluate(() => window.petDesktop.getChatSnapshot());
    const saved = await readFile(file, 'utf8');
    await page.locator('#chat-check').click();
    await page.waitForFunction(() => document.querySelector('#chat-check-status').textContent.includes('本地检查通过'));
    assert.deepEqual(await page.evaluate(() => window.petDesktop.getChatSnapshot()), beforeCheck);
    assert.equal(await readFile(file, 'utf8'), saved);
    assert.equal(await desktop.evaluate(() => globalThis.__chatRequestCount), 0, 'Saving/checking configuration must not send a request');
    await assert.rejects(pet.evaluate(() => window.petDesktop.checkChatSettings()), /Only the workshop/);
    await page.locator('#chat-model').fill('unsaved-model'); await page.locator('#chat-check').click();
    await page.waitForFunction(() => document.querySelector('#chat-check-status').textContent.includes('请先保存'));
    await page.locator('#chat-model').fill('test-model');
    await page.locator('#chat-input').fill('你好'); await page.locator('#chat-send').click();
    await page.waitForFunction(() => document.querySelector('#chat-log [data-reply-state="partial"]')?.textContent.includes('你好，'));
    assert.equal(await page.locator('#chat-send').isDisabled(), true);
    await pet.waitForFunction(() => document.querySelector('#pet-message').textContent === '你好，', undefined, { polling: 100 });
    assert.equal(await pet.locator('#pet-read-aloud').isHidden(), true, 'Partial text must not be offered for speech');
    await desktop.evaluate(() => {
      const response = { status: 'completed', output: [{ type: 'message', content: [{ type: 'output_text', text: '你好，桌宠！<img src=x>' }] }] };
      globalThis.__chatStream.enqueue(new TextEncoder().encode('data: ' + JSON.stringify({ type: 'response.completed', response }) + '\n\n'));
      globalThis.__chatStream.close(); delete globalThis.__chatStream;
    });
    await page.waitForFunction(() => document.querySelector('#chat-log').textContent.includes('你好，桌宠！'));
    assert.equal(await page.locator('#chat-log [data-reply-state="partial"]').count(), 0);
    assert.equal(await page.locator('#chat-log p').count(), 2);
    assert.equal(await page.locator('#chat-log img').count(), 0);
    await pet.waitForFunction(() => document.querySelector('#pet-message').textContent.includes('你好，桌宠！'), undefined, { polling: 100 });
    assert.equal(await pet.locator('#pet-read-aloud').isHidden(), false, 'A complete reply should be available to read aloud');
    await assert.rejects(pet.evaluate(() => window.petDesktop.sendChat('越权')), /Only the workshop/);
    await page.locator('#pet-scale').selectOption('0.8');
    await pet.waitForFunction(() => document.querySelector('.pet-shell').getBoundingClientRect().width < 300);
    for (const id of ['workshop-button', 'pet-chat-toggle', 'pet-voice-input', 'pet-wave', 'pet-read-aloud', 'click-through', 'hide-pet']) {
      const button = pet.locator(`#${id}`);
      await button.evaluate(element => element.scrollIntoView({ inline: 'nearest', block: 'nearest' }));
      const hit = await button.evaluate(element => {
        const bounds = element.getBoundingClientRect();
        const target = document.elementFromPoint(bounds.left + bounds.width / 2, bounds.top + bounds.height / 2);
        return target === element || element.contains(target);
      });
      assert.equal(hit, true, `Pet toolbar button ${id} must be reachable at 80% scale`);
    }
    await page.locator('#pet-scale').selectOption('1.2');
    await pet.waitForFunction(() => document.querySelector('.pet-shell').getBoundingClientRect().width > 300);
    await pet.locator('#pet-controls').evaluate(element => { element.scrollLeft = 0; });
    await desktop.evaluate(() => { globalThis.fetch = async () => new Response(JSON.stringify({ status: 'completed', output: [{ type: 'message', content: [{ type: 'output_text', text: '桌宠直接回复成功' }] }] })); });
    await pet.locator('#pet-chat-toggle').click();
    await pet.locator('#pet-chat-input').fill('桌宠直接发消息');
    await pet.locator('#pet-chat-input').press('Enter');
    await page.waitForFunction(() => document.querySelector('#chat-log').textContent.includes('桌宠直接发消息') && document.querySelector('#chat-log').textContent.includes('桌宠直接回复成功'));
    await pet.waitForFunction(() => document.querySelector('#pet-message').textContent === '桌宠直接回复成功');
    assert.equal(await page.locator('#chat-log p').count(), 4, 'Pet message and reply must sync into workshop history');
    await desktop.evaluate(() => { globalThis.fetch = () => new Promise(resolve => { globalThis.__petCancelReply = resolve; }); });
    await pet.locator('#pet-chat-toggle').click();
    await pet.locator('#pet-chat-input').fill('桌宠待取消消息');
    await pet.locator('#pet-chat-input').press('Enter');
    await pet.locator('#pet-chat-cancel').waitFor({ state: 'visible' });
    await pet.locator('#pet-chat-toggle').click();
    await pet.locator('#pet-chat-input').fill('取消期间新写的草稿');
    await pet.locator('#pet-chat-cancel').click();
    await pet.waitForFunction(() => document.querySelector('#pet-message').textContent.includes('取消期间新写的草稿'));
    await pet.locator('#pet-chat-toggle').click();
    assert.equal(await pet.locator('#pet-chat-input').inputValue(), '取消期间新写的草稿', 'Cancelling an older request must preserve a newer pet draft');
    assert.equal((await page.evaluate(() => window.petDesktop.getChatSnapshot())).history.length, 4, 'Cancelled pet messages must stay out of completed history');
    assert.equal((await page.evaluate(() => window.petDesktop.getChatSnapshot())).attempt.status, 'cancelled');
    await pet.locator('#pet-chat-input').fill('无更新时取消需恢复原草稿');
    await pet.locator('#pet-chat-input').press('Enter');
    await pet.locator('#pet-chat-cancel').waitFor({ state: 'visible' });
    await pet.locator('#pet-chat-cancel').click();
    await pet.waitForFunction(() => document.querySelector('#pet-message').textContent.includes('无更新时取消需恢复原草稿'));
    await pet.locator('#pet-chat-toggle').click();
    assert.equal(await pet.locator('#pet-chat-input').inputValue(), '无更新时取消需恢复原草稿', 'Cancel must restore the sent draft when no newer draft exists');
    await pet.locator('#pet-chat-close').click();
    await desktop.evaluate(() => { globalThis.__petCancelReply?.(new Response('late pet reply')); delete globalThis.__petCancelReply; });
    await desktop.evaluate(() => { globalThis.fetch = async () => new Response(new ReadableStream({ start(controller) {
      globalThis.__chatBrokenStream = controller;
      controller.enqueue(new TextEncoder().encode('data: {"type":"response.output_text.delta","delta":"还没结束","output_index":0,"content_index":0}\n\n'));
    } }), { headers: { 'content-type': 'text/event-stream' } }); });
    await page.locator('#chat-input').fill('中断的消息'); await page.locator('#chat-send').click();
    await page.waitForFunction(() => document.querySelector('#chat-log [data-reply-state="partial"]')?.textContent.includes('还没结束'));
    await desktop.evaluate(() => { globalThis.__chatBrokenStream.error(new Error('private upstream failure')); delete globalThis.__chatBrokenStream; });
    await page.waitForFunction(() => document.querySelector('#chat-log [data-reply-state="incomplete"]') !== null);
    assert.equal(await page.locator('#chat-input').inputValue(), '中断的消息');
    assert.equal((await page.locator('#chat-status').textContent()).includes('private upstream'), false);
    await desktop.evaluate(() => { globalThis.fetch = async () => new Response(JSON.stringify({ status: 'completed', output: [{ type: 'message', content: [{ type: 'output_text', text: '恢复后的完整回复' }] }] })); });
    await page.locator('#chat-input').fill('新草稿'); await page.locator('#chat-retry').click();
    await page.waitForFunction(() => document.querySelector('#chat-log').textContent.includes('恢复后的完整回复'));
    assert.equal(await page.locator('#chat-log [data-reply-state="incomplete"]').count(), 0);
    assert.equal(await page.locator('#chat-input').inputValue(), '新草稿');
    const count = await page.locator('#chat-log p').count();
    await page.locator('#chat-input').fill('输入法草稿');
    await page.locator('#chat-input').evaluate(input => input.dispatchEvent(new KeyboardEvent('keydown', { key: 'Enter', ctrlKey: true, isComposing: true, bubbles: true })));
    assert.equal(await page.locator('#chat-log p').count(), count);
    await desktop.evaluate(() => { globalThis.fetch = async () => new Response('private-error-body', { status: 429 }); });
    await page.locator('#chat-input').fill('失败草稿'); await page.locator('#chat-input').press('Control+Enter');
    await page.waitForFunction(() => document.querySelector('#chat-status').textContent.includes('HTTP 429'));
    assert.equal(await page.locator('#chat-input').inputValue(), '失败草稿');
    assert.equal(await page.locator('#chat-log [data-delivery="failed"]').count(), 1);
    await desktop.evaluate(() => { globalThis.fetch = async () => new Response(JSON.stringify({ error: { code: 'credit_balance_exhausted', message: 'private billing details' } }), { status: 429 }); });
    await page.locator('#chat-retry').click();
    await page.waitForFunction(() => document.querySelector('#chat-status').textContent.includes('额度或限额不足'));
    assert.equal((await page.locator('#chat-status').textContent()).includes('private billing'), false);
    await desktop.evaluate(() => { globalThis.fetch = async (_url, options) => new Response(JSON.stringify({ status: 'completed', output: [{ type: 'message', content: [{ type: 'output_text', text: '重试成功：' + JSON.parse(options.body).input.at(-1).content }] }] })); });
    await page.locator('#chat-input').fill('后续草稿'); await page.locator('#chat-retry').click();
    await page.waitForFunction(() => document.querySelector('#chat-log').textContent.includes('重试成功：失败草稿'));
    assert.equal(await page.locator('#chat-input').inputValue(), '后续草稿');
    assert.equal(await page.locator('#chat-log [data-delivery="failed"]').count(), 0);
    assert.equal(await page.locator('#chat-log [data-delivery]').filter({ hasText: '失败草稿' }).count(), 1);
    await desktop.evaluate(() => { globalThis.fetch = () => new Promise(resolve => { globalThis.__chatLateReply = resolve; }); });
    await page.locator('#chat-input').fill('待取消'); await page.locator('#chat-send').click();
    await page.locator('#chat-input').fill('取消期间的新草稿');
    await page.locator('#chat-cancel').click();
    await page.waitForFunction(() => document.querySelector('#chat-status').textContent.includes('已取消'));
    assert.equal(await page.locator('#chat-input').inputValue(), '取消期间的新草稿');
    await page.locator('#chat-clear').click(); await page.waitForFunction(() => document.querySelector('#chat-log').children.length === 0);
    await pet.waitForFunction(() => document.querySelector('#pet-read-aloud').hidden);
    assert.equal(await page.locator('#chat-retry').isHidden(), true);
    await desktop.evaluate(() => { globalThis.__chatLateReply?.(new Response('late ignored response')); delete globalThis.__chatLateReply; });
    await desktop.evaluate(() => { globalThis.fetch = async () => new Response(new ReadableStream({ start(controller) {
      globalThis.__chatCancelStream = controller;
      controller.enqueue(new TextEncoder().encode('data: {"type":"response.output_text.delta","delta":"取消前片段","output_index":0,"content_index":0}\n\n'));
    } }), { headers: { 'content-type': 'text/event-stream' } }); });
    await page.locator('#chat-input').fill('流式取消'); await page.locator('#chat-send').click();
    await page.waitForFunction(() => document.querySelector('#chat-log [data-reply-state="partial"]')?.textContent.includes('取消前片段'));
    await page.locator('#chat-cancel').click();
    await page.waitForFunction(() => document.querySelector('#chat-status').textContent.includes('已取消'));
    assert.equal(await page.locator('#chat-log [data-reply-state="incomplete"]').count(), 1);
    assert.equal(await page.locator('#chat-input').inputValue(), '流式取消');
    await page.locator('#chat-clear').click(); await page.waitForFunction(() => document.querySelector('#chat-log').children.length === 0);
    await desktop.evaluate(() => { globalThis.__chatCancelStream.error(new Error('late cancelled stream')); delete globalThis.__chatCancelStream; });
    await page.locator('#chat-model').fill('invalid model!'); await page.locator('#chat-forget').click();
    await page.waitForFunction(() => document.querySelector('#chat-status').textContent.includes('请设置'));
    assert.equal(await page.locator('#chat-model').inputValue(), 'test-model');
    assert.equal(await page.locator('#chat-send').isDisabled(), true);
    assert.equal((await page.evaluate(() => window.petDesktop.getChatSettings())).hasKey, false);
    await page.locator('#chat-key').fill('smoke-key-not-real'); await page.locator('#chat-save').click();
    await page.waitForFunction(() => document.querySelector('#chat-status').textContent.includes('配置已保存'));
  } finally { await desktop.evaluate(() => {
    for (const key of ['__chatStream', '__chatBrokenStream', '__chatCancelStream']) { try { globalThis[key]?.error(new Error('test cleanup')); } catch {} delete globalThis[key]; }
    globalThis.__petCancelReply?.(new Response('cleanup')); delete globalThis.__petCancelReply;
    globalThis.fetch = globalThis.__chatOriginalFetch; delete globalThis.__chatOriginalFetch;
    delete globalThis.__chatRequestCount;
  }); }
}
